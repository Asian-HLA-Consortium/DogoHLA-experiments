"""Tables for results/MOSAIC_TYPER_REPORT.md from results/SCORES_test.json (frozen scorer output).
  python report.py    -> results/REPORT_TABLES.md (the narrative report quotes these tables)
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C


def f(x):
    return f"{x['correct']}/{x['n']} ({100 * x['correct'] / x['n']:.1f}%)" if x['n'] else '0/0'


def ci(u):
    if u.get('difference_pp') is None:
        return 'n/a'
    lo, hi = u['bootstrap95_pp']
    return (f"{u['difference_pp']:+.2f} pp [{lo:+.2f}, {hi:+.2f}], p={u['sign_flip_p']:.3g}, "
            f"+{u['gains']}/-{u['losses']} of {u['n']}")


def main():
    S = C.load_json(C.S / 'results/SCORES_test.json')['summary']
    L = ['# Report tables (generated by src/report.py from results/SCORES_test.json)', '']
    for rs, arms in S.items():
        L += [f'## {rs}', '', '| arm | recovery (all IPD-absent) | recovery, final call | recovery (IPD-only mosaic) | '
              '4-field named (IPD-present) | 3-field decoded | 2-field decoded | final MOS calls | false MOS |',
              '|---|---|---|---|---|---|---|---:|---:|']
        for arm, v in arms.items():
            if arm == 'contrasts':
                continue
            L.append(f"| {arm} | {f(v['recovery_all_absent'])} | {f(v['recovery_final_all_absent'])} | "
                     f"{f(v['recovery_ipd_only_mosaic'])} | {f(v['named4_present'])} | {f(v['named3_decoded'])} | "
                     f"{f(v['named2_decoded'])} | {v['final_mos']} | {v['false_mos']} |")
        L += ['', '| contrast | recovery (all IPD-absent) | recovery (IPD-only mosaic) | 4-field named | 2-field decoded |',
              '|---|---|---|---|---|']
        for k, v in arms.get('contrasts', {}).items():
            L.append(f"| {k} | {ci(v['recovery_all_absent'])} | {ci(v['recovery_ipd_only_mosaic'])} | "
                     f"{ci(v['named4_present'])} | {ci(v['named2_decoded'])} |")
        L += ['', '| arm | false MOS by truth class |', '|---|---|']
        for arm, v in arms.items():
            if arm != 'contrasts':
                L.append(f"| {arm} | " + ', '.join(f'{k} {n}' for k, n in v['false_mos_by_class'].items() if n)
                         + f" (copies by class: {v['copies_by_class']}) |")
        L += ['', '| gene | ' + ' | '.join(f'{a} recovery | {a} 4-field' for a in arms if a != 'contrasts') + ' |',
              '|---|' + '---|---|' * (len(arms) - 1)]
        for g in C.GENES:
            L.append(f'| {g} | ' + ' | '.join(f"{f(v['per_gene'][g]['recovery'])} | {f(v['per_gene'][g]['named4'])}"
                                             for a, v in arms.items() if a != 'contrasts') + ' |')
        L.append('')
    (C.S / 'results/REPORT_TABLES.md').write_text('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
